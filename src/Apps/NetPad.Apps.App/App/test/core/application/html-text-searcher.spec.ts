import {HtmlTextSearcher} from "@application/find-text-box/html-text-searcher";

const runTest = (initialHtml: string, searchForText: string, expectedHtml: string) => {
    const fragment = document.createDocumentFragment();
    const p = document.createElement("p");
    p.innerHTML = initialHtml;
    fragment.appendChild(p);

    const searcher = new HtmlTextSearcher();

    const results = searcher.search(fragment as unknown as HTMLElement, searchForText, "p");

    if (initialHtml === expectedHtml)
        expect(results.length).toBe(0);
    else
        expect(results.length).toBeGreaterThan(0);

    expect(p.innerHTML).toBe(expectedHtml);
};

// Used to simulate how text is rendered in HTML as generated by NetPad
const toHtml = (text: string) => {
    let html = "";
    let insideXml = false;

    for (let char of text) {
        if (char === "<") {
            html += char;
            insideXml = true;
            continue;
        }

        if (char === ">") {
            html += char;
            insideXml = false;
            continue;
        }

        if (insideXml) {
            html += char;
            continue;
        }

        if (char === " ") char = "&nbsp;";
        else if (char === "&") char = "&amp;";
        else if (char === "<") char = "&lt;";
        else if (char === ">") char = "&gt;";
        else if (char === "\n") char = "<br>";

        html += char;
    }

    return html;
};

describe.each([
    ["Should not match anything", "none", `Should not match anything`],
    ["My name is Joe", "name", `My <span class="text-search-result">name</span> is Joe`],
    ["Names are important", "name", `<span class="text-search-result">Name</span>s are important`],
    ["I like my namE", "nAme", `I like my <span class="text-search-result">namE</span>`],
])("Find Text Search implementation 1 - Simple Search", (initialHtml: string, searchForText: string, expectedHtml: string) => {
    test(`searching "${initialHtml}" for "${searchForText}" results in "${expectedHtml}"`, () => {
        runTest(toHtml(initialHtml), searchForText, toHtml(expectedHtml));
    });
});

describe.each([
    ["My name is Joe", "name is", `My <span class="text-search-result">name is</span> Joe`],
    [" My name is Joe", " my", `<span class="text-search-result"> My</span> name is Joe`],
    ["My name is", " ", `My<span class="text-search-result"> </span>name<span class="text-search-result"> </span>is`],
    ["My name is Beck", "b", `My name is <span class="text-search-result">B</span>eck`],
    ["My \n name is Beck", "name", `My \n <span class="text-search-result">name</span> is Beck`],
])("Find Text Search implementation 1 - Spaces & Breaks", (initialHtml: string, searchForText: string, expectedHtml: string) => {
    test(`searching "${initialHtml}" for "${searchForText}" results in "${expectedHtml}"`, () => {
        runTest(toHtml(initialHtml), searchForText, toHtml(expectedHtml));
    });
});

describe.each([
    ["I like apples & oranges", "apples & oranges", `I like <span class="text-search-result">apples & oranges</span>`],
    ["I like apples & oranges", "apples &amp; oranges", `I like apples & oranges`],
    [`I like "apples" & 'oranges'`, `"apples" & 'oranges'`, `I like <span class="text-search-result">"apples" & 'oranges'</span>`],
    [`I like "apples" & 'oranges'`, `"`, `I like <span class="text-search-result">"</span>apples<span class="text-search-result">"</span> & 'oranges'`],
    [`I like "apples" & 'oranges'`, `'`, `I like "apples" & <span class="text-search-result">'</span>oranges<span class="text-search-result">'</span>`],
    ["1&nbsp;is&nbsp;&lt;&nbsp;than&nbsp;10", "is < than", `1&nbsp;<span class="text-search-result">is&nbsp;&lt;&nbsp;than</span>&nbsp;10`],
    ["10&nbsp;is&nbsp;&gt;&nbsp;than&nbsp;1", "is > than", `10&nbsp;<span class="text-search-result">is&nbsp;&gt;&nbsp;than</span>&nbsp;1`],
])("Find Text Search implementation 1 - Special Characters/Strings", (initialHtml: string, searchForText: string, expectedHtml: string) => {
    test(`searching "${initialHtml}" for "${searchForText}" results in "${expectedHtml}"`, () => {
        const skipLessAndGreaterThanHtmlConversion = initialHtml.indexOf("&lt;") >= 0 || initialHtml.indexOf("&gt;") >= 0;
        runTest(
            skipLessAndGreaterThanHtmlConversion ? initialHtml : toHtml(initialHtml),
            searchForText,
            skipLessAndGreaterThanHtmlConversion ? expectedHtml : toHtml(expectedHtml));
    });
});

describe("Find Text Search - search units", () => {
    // jsdom has no checkVisibility; this stands in for its check for a `display: none` ancestor.
    beforeAll(() => {
        Element.prototype.checkVisibility = function (this: Element) {
            for (let element: Element | null = this; element; element = element.parentElement) {
                if (getComputedStyle(element).display === "none") return false;
            }
            return true;
        };
    });

    afterAll(() => delete (Element.prototype as Partial<Element>).checkVisibility);

    afterEach(() => document.body.replaceChildren());

    const mount = (html: string) => {
        const root = document.createElement("div");
        root.innerHTML = html;
        document.body.appendChild(root);
        return root;
    };

    const search = (root: HTMLElement, text: string) => new HtmlTextSearcher().search(root, text, ".unit");

    const textNodeCount = (element: Element) => {
        const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
        let count = 0;
        while (walker.nextNode()) count++;
        return count;
    };

    test("matches a phrase that crosses spans, ignoring case", () => {
        const root = mount(`<div class="unit"><span class="sql-keyword">FROM</span> "albums" AS a</div>`);

        const matches = search(root, `from "ALBUMS"`);

        expect(matches.length).toBe(1);
        expect(matches[0].map(part => part.textContent)).toEqual(["FROM", ` "albums"`]);
        expect(root.querySelector(".sql-keyword")!.innerHTML).toBe(`<span class="text-search-result">FROM</span>`);
    });

    test("does not match across a line break", () => {
        const root = mount(`<div class="unit">dbug:<br>11/3</div>`);

        expect(search(root, "dbug:11").length).toBe(0);
        expect(search(root, "dbug:").length).toBe(1);
    });

    test("does not match across two units", () => {
        const root = mount(`<div class="unit">ab</div><div class="unit">cd</div>`);

        expect(search(root, "bc").length).toBe(0);
    });

    test("searches a nested unit on its own, apart from its parent", () => {
        const root = mount(`<div class="unit">ab<span class="unit">cd</span>ef</div>`);

        expect(search(root, "cd").length).toBe(1);
        expect(search(root, "bc").length).toBe(0);
        expect(search(root, "be").length).toBe(0);
    });

    test("skips a unit that is not shown", () => {
        const root = mount(
            `<style>.log-by-query { display: none; } .show-query .log-by-query { display: block; }</style>`
            + `<div class="unit">SELECT 1</div><div class="unit log-by-query">SELECT 2</div>`);

        expect(search(root, "select").length).toBe(1);

        root.classList.add("show-query");

        expect(search(root, "select").length).toBe(2);
    });

    test("matches a space against a no-break space, and finds & and < as text", () => {
        const root = mount(`<div class="unit">x&nbsp;&amp; <i>&lt;y&gt;</i></div>`);

        const matches = search(root, "x & <y>");

        expect(matches.length).toBe(1);
        expect(matches[0].map(part => part.textContent)).toEqual(["x\u00a0& ", "<y>"]);
    });

    test("counts matches, not the parts that highlight them", () => {
        const root = mount(`<div class="unit">a<b>b</b> a<b>b</b></div>`);

        const matches = search(root, "ab");

        expect(matches.length).toBe(2);
        expect(matches.map(match => match.length)).toEqual([2, 2]);
        expect(root.querySelectorAll(".text-search-result").length).toBe(4);
    });

    test("clearing restores the unit's text without leaving split text nodes", () => {
        const root = mount(`<div class="unit">ab<b>abc</b>ba</div>`);
        const unit = root.querySelector(".unit")!;
        const html = unit.innerHTML;
        const nodes = textNodeCount(unit);

        for (const text of ["a", "b", "ab", "bc"]) {
            search(root, text);
        }

        expect(search(root, "").length).toBe(0);
        expect(unit.innerHTML).toBe(html);
        expect(textNodeCount(unit)).toBe(nodes);
    });
});
